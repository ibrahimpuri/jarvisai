// Which way each room plays, for the guide: for every room, and every room she can come into it from, the rooms she
// can go on to from there, by Maren's movement (tools/reach.js) with each set of tools she can have. Rooms that only
// play one way (a drop, a chute, a pit she cannot climb out of on the far side) are why the shortest way through the
// rooms is not always a way at all. Written to godot/data/through.json, which godot/src/Game/Guide.cs reads.
//   node tools/throughs.js
'use strict';
const fs = require('fs');
const path = require('path');
const { analyse, H, W, TG, breakCrystals } = require('./reach.js');

const GW = Math.max(...H.ROOMS.map((r) => r.col + r.w)) * 40;
const TIERS = {
  swing: ['swing'], boots: ['swing', 'boots'], jet: ['swing', 'boots', 'jet'],
  tidekey: ['swing', 'boots', 'jet', 'tidekey'], seal: ['swing', 'boots', 'jet', 'tidekey', 'seal'],
};
// every door the story opens, open: the guide checks those itself, door by door, as the game stands
const FLAGS = { seawallOpen: true, basinFilling: true, basinCrossed: true, abbotDead: true, almonerDead: true, priorWedged: true, precentorDead: true,
  motherDead: true, liftDropped: true, undertowDead: true, skullOpen: true, shoalDead: true };

const out = { note: 'generated by tools/throughs.js; do not edit', tiers: {} };
for (const [tier, abil] of Object.entries(TIERS)) {
  W.reset();
  W.state('saltgate').pool = { basin: 7 }; W.state('choir').choirLevel = 3;
  { const r = H.ROOM.priors; for (let y = 17; y < 23; y++) W.setChar(r.ox + 21, r.oy + y, 'H'); }
  { const c = H.ROOM.choir; for (let y = 0; y < 23; y++) for (const x of [4, 32]) if (W.charAt(c.ox + x, c.oy + y) === 'C') W.setChar(c.ox + x, c.oy + y, ' '); }
  for (const r of H.ROOMS) if (r.crystals) breakCrystals(r.id);
  for (const r of H.ROOMS) for (let y = 0; y < r.th; y++) for (let x = 0; x < r.tw; x++) if (W.charAt(r.ox + x, r.oy + y) === 'S') W.setChar(r.ox + x, r.oy + y, ' ');
  const t0 = Date.now();
  const seen = analyse(abil, FLAGS, [], { edges: true });
  // the moves, cell to cell, split into those within a room and those from one room to the next
  const roomOf = (i) => W.roomAtTile(i % GW, Math.floor(i / GW))?.id;
  const inner = new Map(), cross = [];
  const GH = Math.max(...H.ROOMS.map((r) => r.row + r.h)) * 23;
  for (const e of seen.edges) {
    const a = Math.floor(e / (GW * GH)), b = e % (GW * GH);
    const ra = roomOf(a), rb = roomOf(b);
    if (!ra || !rb) continue;
    if (ra === rb) { if (!inner.has(a)) inner.set(a, []); inner.get(a).push(b); }
    else cross.push([a, b, ra, rb]);
  }
  const into = {}, outOf = {};
  for (const [a, b, ra, rb] of cross) {
    ((into[rb] = into[rb] || {})[ra] = into[rb][ra] || []).push(b);
    (outOf[a] = outOf[a] || []).push(rb);
  }
  const table = {};
  for (const r of H.ROOMS) {
    const ways = {};
    for (const [from, cells] of Object.entries(into[r.id] || {})) {
      // everywhere in the room she can get to from where she came in, and the rooms she can leave it for
      const s = new Set(cells), q = [...cells];
      while (q.length) { const i = q.pop(); for (const j of inner.get(i) || []) if (!s.has(j)) { s.add(j); q.push(j); } }
      const exits = new Set();
      for (const i of s) for (const rb of outOf[i] || []) if (rb !== r.id) exits.add(rb);
      ways[from] = [...exits].sort();
    }
    if (Object.keys(ways).length) table[r.id] = ways;
  }
  out.tiers[tier] = table;
  console.log(`${tier}: ${Object.keys(table).length} rooms, ${seen.size} cells, ${seen.edges.size} moves, ${((Date.now() - t0) / 1000).toFixed(0)}s`);
}
// the ways in that lead nowhere new: a room she can come into from A but go on from only to where she came from
for (const [tier, table] of Object.entries(out.tiers)) {
  const dead = [];
  for (const [r, ways] of Object.entries(table)) {
    const nbs = new Set([...Object.keys(ways), ...Object.values(ways).flat()]);
    for (const [from, exits] of Object.entries(ways)) {
      const missing = [...nbs].filter((n) => n !== from && !exits.includes(n));
      if (missing.length) dead.push(`${r} from ${from} cannot reach ${missing.join(',')}`);
    }
  }
  console.log(`  ${tier}: ${dead.length} one-way crossings` + (tier === 'seal' || tier === 'swing' ? '\n    ' + dead.join('\n    ') : ''));
}
fs.writeFileSync(path.join(__dirname, '..', 'godot', 'data', 'through.json'), JSON.stringify(out));
console.log('wrote godot/data/through.json');
