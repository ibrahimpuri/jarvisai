// The island, room by room. Each screen is 40x23 tiles; rooms sit on one world grid
// (col,row in screens) so the tide can be expressed as a single world-space water line.
//
// Tiles
//   #  stone          _  invisible boundary   T  timber (wall-hang)   R  rib bone (wall-hang)
//   M  metal floor    P  creaking boards      =  one-way timber       b  rigging (burns away)
//   S  salt wall (fire or picks break it)     x  salt crystals (hurt)  o  iron ring (gaff swing)
//   H  ladder         E  ebb gate (open while Ebbing)   L  tide door (open at Low)
//   V  Prior's door   C  crystal wall         K  seawall gate         Z  skull door
//   Y  choir gate (open once drained)         y  stair (solid only once drained)
//   h  sluice hatch   G  floor grate          f  falling water
//   |  pillar (bg)    w  stained glass (bg)   a  air vent
// Any other character is looked up in the room's `ents` legend.
